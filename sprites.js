function sprite(rows) {
    const width = Math.max(...rows.map((row) => row.length));
    const grid = rows.map((row) => row.padEnd(width, ".").split("").map((c) => c === "#"));
    return { grid, cols: width, rowsCount: rows.length, w: width * PIXEL, h: rows.length * PIXEL };
}

